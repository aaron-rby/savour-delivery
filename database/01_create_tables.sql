-- Clean teardown of existing objects in reverse dependency order
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'DELIVERY', 'PAYMENT', 'ORDER_ITEM', 'FOOD_ORDER', 
        'MENU_ITEM', 'RESTAURANT', 'DELIVERY_PARTNER', 'CUSTOMER', 'APP_USER'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ----------------------------------------------------------------------------
-- 1. APP_USER: Base entity for all actors (Customers and Delivery Partners)
-- ----------------------------------------------------------------------------
CREATE TABLE APP_USER (
    user_id     NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    full_name   VARCHAR2(100) NOT NULL,
    email       VARCHAR2(120) NOT NULL CONSTRAINT uq_app_user_email UNIQUE,
    phone       VARCHAR2(20)  NOT NULL CONSTRAINT chk_app_user_phone CHECK (LENGTH(phone) >= 10)
);

-- ----------------------------------------------------------------------------
-- 2. CUSTOMER: Role specialization of APP_USER (Overlapping/Total Subtype)
-- ----------------------------------------------------------------------------
CREATE TABLE CUSTOMER (
    user_id         NUMBER PRIMARY KEY,
    customer_since  DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_customer_user FOREIGN KEY (user_id) 
        REFERENCES APP_USER(user_id) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 3. DELIVERY_PARTNER: Role specialization of APP_USER
-- ----------------------------------------------------------------------------
CREATE TABLE DELIVERY_PARTNER (
    user_id             NUMBER PRIMARY KEY,
    transport_mode      VARCHAR2(30) NOT NULL CONSTRAINT chk_partner_transport 
        CHECK (transport_mode IN ('BIKE', 'SCOOTER', 'ELECTRIC_VEHICLE', 'BICYCLE')),
    availability_status VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL CONSTRAINT chk_partner_status 
        CHECK (availability_status IN ('AVAILABLE', 'BUSY', 'OFFLINE')),
    CONSTRAINT fk_partner_user FOREIGN KEY (user_id) 
        REFERENCES APP_USER(user_id) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 4. RESTAURANT: Merchant catalog entity
-- ----------------------------------------------------------------------------
CREATE TABLE RESTAURANT (
    restaurant_id   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    restaurant_name VARCHAR2(120) NOT NULL,
    address_line    VARCHAR2(200) NOT NULL,
    city            VARCHAR2(80)  NOT NULL,
    postal_code     VARCHAR2(20)  NOT NULL,
    contact_phone   VARCHAR2(20)  NOT NULL
);

-- ----------------------------------------------------------------------------
-- 5. MENU_ITEM: Items offered by a specific restaurant
-- ----------------------------------------------------------------------------
CREATE TABLE MENU_ITEM (
    item_id         NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    restaurant_id   NUMBER NOT NULL,
    item_name       VARCHAR2(120) NOT NULL,
    category        VARCHAR2(60)  NOT NULL,
    current_price   NUMBER(10,2)  NOT NULL CONSTRAINT chk_menu_item_price CHECK (current_price > 0),
    is_available    NUMBER(1) DEFAULT 1 NOT NULL CONSTRAINT chk_menu_item_available CHECK (is_available IN (0, 1)),
    CONSTRAINT fk_menu_item_restaurant FOREIGN KEY (restaurant_id) 
        REFERENCES RESTAURANT(restaurant_id) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 6. FOOD_ORDER: Order header record capturing destination and delivery fee
-- ----------------------------------------------------------------------------
CREATE TABLE FOOD_ORDER (
    order_id            NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    customer_id         NUMBER NOT NULL,
    restaurant_id       NUMBER NOT NULL,
    ordered_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    order_status        VARCHAR2(30) DEFAULT 'PLACED' NOT NULL CONSTRAINT chk_order_status 
        CHECK (order_status IN ('PLACED', 'ACCEPTED', 'PREPARING', 'READY', 'OUT_FOR_DELIVERY', 'DELIVERED', 'CANCELLED')),
    dropoff_line        VARCHAR2(200) NOT NULL,
    dropoff_city        VARCHAR2(80)  NOT NULL,
    dropoff_postal_code VARCHAR2(20)  NOT NULL,
    delivery_fee        NUMBER(10,2) DEFAULT 0.00 NOT NULL CONSTRAINT chk_order_delivery_fee CHECK (delivery_fee >= 0),
    CONSTRAINT fk_order_customer FOREIGN KEY (customer_id) 
        REFERENCES CUSTOMER(user_id),
    CONSTRAINT fk_order_restaurant FOREIGN KEY (restaurant_id) 
        REFERENCES RESTAURANT(restaurant_id)
);

-- ----------------------------------------------------------------------------
-- 7. ORDER_ITEM: Weak bridge relation preserving historical agreed price
-- ----------------------------------------------------------------------------
CREATE TABLE ORDER_ITEM (
    order_id            NUMBER NOT NULL,
    item_id             NUMBER NOT NULL,
    quantity            NUMBER(4) NOT NULL CONSTRAINT chk_order_item_qty CHECK (quantity > 0),
    agreed_unit_price   NUMBER(10,2) NOT NULL CONSTRAINT chk_order_item_price CHECK (agreed_unit_price > 0),
    CONSTRAINT pk_order_item PRIMARY KEY (order_id, item_id),
    CONSTRAINT fk_order_item_order FOREIGN KEY (order_id) 
        REFERENCES FOOD_ORDER(order_id) ON DELETE CASCADE,
    CONSTRAINT fk_order_item_item FOREIGN KEY (item_id) 
        REFERENCES MENU_ITEM(item_id)
);

-- ----------------------------------------------------------------------------
-- 8. PAYMENT: Transaction record (At most one per order)
-- ----------------------------------------------------------------------------
CREATE TABLE PAYMENT (
    payment_id      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    order_id        NUMBER NOT NULL CONSTRAINT uq_payment_order UNIQUE,
    payment_method  VARCHAR2(40) NOT NULL CONSTRAINT chk_payment_method 
        CHECK (payment_method IN ('UPI', 'CARD', 'NET_BANKING', 'CASH_ON_DELIVERY')),
    payment_amount  NUMBER(10,2) NOT NULL CONSTRAINT chk_payment_amount CHECK (payment_amount > 0),
    payment_status  VARCHAR2(30) DEFAULT 'PENDING' NOT NULL CONSTRAINT chk_payment_status 
        CHECK (payment_status IN ('PENDING', 'COMPLETED', 'FAILED')),
    paid_at         TIMESTAMP,
    CONSTRAINT fk_payment_order FOREIGN KEY (order_id) 
        REFERENCES FOOD_ORDER(order_id) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 9. DELIVERY: Fulfillment record (At most one per order, assigned to partner)
-- ----------------------------------------------------------------------------
CREATE TABLE DELIVERY (
    order_id        NUMBER PRIMARY KEY,
    partner_id      NUMBER NOT NULL,
    assigned_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    picked_up_at    TIMESTAMP,
    delivered_at    TIMESTAMP,
    CONSTRAINT fk_delivery_order FOREIGN KEY (order_id) 
        REFERENCES FOOD_ORDER(order_id) ON DELETE CASCADE,
    CONSTRAINT fk_delivery_partner FOREIGN KEY (partner_id) 
        REFERENCES DELIVERY_PARTNER(user_id),
    CONSTRAINT chk_delivery_times CHECK (
        picked_up_at IS NULL OR picked_up_at >= assigned_at
    ),
    CONSTRAINT chk_delivery_delivered CHECK (
        delivered_at IS NULL OR (picked_up_at IS NOT NULL AND delivered_at >= picked_up_at)
    )
);

-- Performance Indexes for foreign key lookups and reporting queries
CREATE INDEX idx_menu_item_rest ON MENU_ITEM(restaurant_id);
CREATE INDEX idx_food_order_cust ON FOOD_ORDER(customer_id);
CREATE INDEX idx_food_order_rest ON FOOD_ORDER(restaurant_id);
CREATE INDEX idx_food_order_status ON FOOD_ORDER(order_status);
CREATE INDEX idx_order_item_item ON ORDER_ITEM(item_id);
CREATE INDEX idx_delivery_partner ON DELIVERY(partner_id);

COMMIT;
