DROP TABLE IF EXISTS DELIVERY CASCADE;
DROP TABLE IF EXISTS PAYMENT CASCADE;
DROP TABLE IF EXISTS ORDER_ITEM CASCADE;
DROP TABLE IF EXISTS FOOD_ORDER CASCADE;
DROP TABLE IF EXISTS MENU_ITEM CASCADE;
DROP TABLE IF EXISTS RESTAURANT CASCADE;
DROP TABLE IF EXISTS DELIVERY_PARTNER CASCADE;
DROP TABLE IF EXISTS CUSTOMER CASCADE;
DROP TABLE IF EXISTS APP_USER CASCADE;

CREATE TABLE APP_USER (
    user_id     NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    full_name   VARCHAR2(100) NOT NULL,
    email       VARCHAR2(120) NOT NULL UNIQUE,
    phone       VARCHAR2(20)  NOT NULL
);

CREATE TABLE CUSTOMER (
    user_id         NUMBER PRIMARY KEY REFERENCES APP_USER(user_id) ON DELETE CASCADE,
    customer_since  DATE DEFAULT CURRENT_DATE NOT NULL
);

CREATE TABLE DELIVERY_PARTNER (
    user_id             NUMBER PRIMARY KEY REFERENCES APP_USER(user_id) ON DELETE CASCADE,
    transport_mode      VARCHAR2(30) NOT NULL,
    availability_status VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL
);

CREATE TABLE RESTAURANT (
    restaurant_id   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    restaurant_name VARCHAR2(120) NOT NULL,
    address_line    VARCHAR2(200) NOT NULL,
    city            VARCHAR2(80)  NOT NULL,
    postal_code     VARCHAR2(20)  NOT NULL,
    contact_phone   VARCHAR2(20)  NOT NULL
);

CREATE TABLE MENU_ITEM (
    item_id         NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    restaurant_id   NUMBER NOT NULL REFERENCES RESTAURANT(restaurant_id) ON DELETE CASCADE,
    item_name       VARCHAR2(120) NOT NULL,
    category        VARCHAR2(60)  NOT NULL,
    current_price   NUMBER(10,2)  NOT NULL CHECK (current_price > 0),
    is_available    NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_available IN (0, 1))
);

CREATE TABLE FOOD_ORDER (
    order_id            NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    customer_id         NUMBER NOT NULL REFERENCES CUSTOMER(user_id),
    restaurant_id       NUMBER NOT NULL REFERENCES RESTAURANT(restaurant_id),
    ordered_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    order_status        VARCHAR2(30) DEFAULT 'PLACED' NOT NULL,
    dropoff_line        VARCHAR2(200) NOT NULL,
    dropoff_city        VARCHAR2(80)  NOT NULL,
    dropoff_postal_code VARCHAR2(20)  NOT NULL,
    delivery_fee        NUMBER(10,2) DEFAULT 0.00 NOT NULL CHECK (delivery_fee >= 0)
);

CREATE TABLE ORDER_ITEM (
    order_id            NUMBER NOT NULL REFERENCES FOOD_ORDER(order_id) ON DELETE CASCADE,
    item_id             NUMBER NOT NULL REFERENCES MENU_ITEM(item_id),
    quantity            NUMBER(4) NOT NULL CHECK (quantity > 0),
    agreed_unit_price   NUMBER(10,2) NOT NULL CHECK (agreed_unit_price > 0),
    PRIMARY KEY (order_id, item_id)
);

CREATE TABLE PAYMENT (
    payment_id      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    order_id        NUMBER NOT NULL UNIQUE REFERENCES FOOD_ORDER(order_id) ON DELETE CASCADE,
    payment_method  VARCHAR2(40) NOT NULL,
    payment_amount  NUMBER(10,2) NOT NULL CHECK (payment_amount > 0),
    payment_status  VARCHAR2(30) DEFAULT 'PENDING' NOT NULL,
    paid_at         TIMESTAMP
);

CREATE TABLE DELIVERY (
    order_id        NUMBER PRIMARY KEY REFERENCES FOOD_ORDER(order_id) ON DELETE CASCADE,
    partner_id      NUMBER NOT NULL REFERENCES DELIVERY_PARTNER(user_id),
    assigned_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    picked_up_at    TIMESTAMP,
    delivered_at    TIMESTAMP
);
